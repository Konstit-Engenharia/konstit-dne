function titleSpelling(word: string) {
  const compact = word.replaceAll('.', '').replaceAll('ª', 'A').replace(/[º°]/g, 'O');
  // Preserve an explicit Dona without expanding the unmarked preposition DA.
  return compact === 'DA' ? 'DONA' : compact;
}

