function wordLookup(groups: Record<string, string[]>): Map<string, string> {
  const lookup = new Map<string, string>();
  for (const [name, aliases,] of Object.entries(groups)) {
    for (const alias of aliases) {
      // Match the first CASE arm when an alias occurs in more than one group.
      if (!lookup.has(alias)) {
        lookup.set(alias, name);
      }
    }
  }
  return lookup;
}

