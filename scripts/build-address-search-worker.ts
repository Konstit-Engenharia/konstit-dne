import { fileURLToPath } from 'node:url';

const entrypoint = fileURLToPath(new URL('../src/address-search-worker.ts', import.meta.url));
const output = Bun.file(new URL('../src/address-search-worker-source.ts', import.meta.url));
const build = await Bun.build({
  entrypoints: [entrypoint],
  target: 'bun',
  format: 'esm',
  splitting: false,
  minify: { syntax: true, whitespace: true, identifiers: false },
  plugins: [{
    name: 'worker-database-path',
    setup(builder) {
      // The parent resolves the package asset. Workers only receive absolute paths or shared bytes.
      builder.onLoad({ filter: /[/\\]bundled-database\.ts$/ }, () => ({
        loader: 'js',
        contents: "throw new Error('Address search workers require a resolved database path'); export default '';",
      }));
    },
  }],
});
if (!build.success) {
  throw new AggregateError(build.logs, 'Unable to bundle the address search worker');
}
const [entry,] = build.outputs;
if (entry?.kind !== 'entry-point' || build.outputs.length !== 1) {
  throw new Error('Address search worker must bundle into one JavaScript file without external assets');
}
const source = await entry.text();
const contents = [
  '// Generated by bun run build:worker. Do not edit by hand.',
  '// biome-ignore lint/suspicious/noTemplateCurlyInString: The generated JavaScript contains its own template literals.',
  `const workerSource: string = ${JSON.stringify(source)};`,
  'export default workerSource;',
  '',
].join('\n');
if (Bun.argv.includes('--check')) {
  if (await output.text() !== contents) {
    throw new Error('Address search worker bundle is stale. Run bun run build:worker.');
  }
} else {
  await Bun.write(output, contents);
}
